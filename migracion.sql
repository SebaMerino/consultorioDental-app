alter table pacientes add column if not exists dni text;
alter table pacientes add column if not exists tratamientos jsonb not null default '[]'::jsonb;
alter table pacientes add column if not exists pagos jsonb not null default '[]'::jsonb;
alter table pacientes add column if not exists odontograma jsonb not null default '{}'::jsonb;

alter table turnos add column if not exists paciente_id bigint;
alter table turnos add column if not exists es_sugerido boolean not null default false;
alter table turnos add column if not exists recurrente text;

